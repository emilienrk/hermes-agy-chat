"""agy tasks: scheduled prompts that agy runs instead of Hermes' paid LLM.

Each task is a Hermes cron job in no_agent mode whose script (generated under
<HERMES_HOME>/scripts/agy-tasks/, where Hermes requires cron scripts to live) runs agy_run.py;
the script's output, agy's answer, is what the job delivers. Hermes keeps the schedule, the
delivery and the job list; tasks.json only remembers which jobs are agy's.

No relative imports: hermes_mcp.py imports this module by path. Runs where Hermes' tools are
importable (the gateway, the MCP bridge).
"""

import json
import os
import re
import secrets
import threading
from pathlib import Path

PLUGIN_DIR = Path(__file__).resolve().parent
RUNNER = PLUGIN_DIR / "agy_run.py"
HERMES_HOME = Path(os.environ.get("HERMES_HOME") or Path.home() / ".hermes")
SCRIPTS_SUBDIR = "agy-tasks"
NAME_PREFIX = "agy · "

_lock = threading.Lock()

SCRIPT_TEMPLATE = '''\
# agy task generated by the agy-chat plugin: Hermes' cron runs this script (no_agent), agy does
# the work. Edit the task with /agy_task in Telegram rather than by hand.
import runpy
import sys

sys.argv = ["agy_run", {task!r}]
runpy.run_path({runner!r}, run_name="__main__")
'''


def _registry_path():
    try:
        from plugins.plugin_storage import plugin_data_dir
        data = plugin_data_dir("agy-chat")
    except Exception:
        data = HERMES_HOME / "plugin-data" / "agy-chat"
        data.mkdir(parents=True, exist_ok=True)
    return data / "tasks.json"


def _load():
    try:
        return json.loads(_registry_path().read_text())
    except (OSError, ValueError):
        return {}


def _save(tasks):
    path = _registry_path()
    tmp = path.with_suffix(".tmp")
    tmp.write_text(json.dumps(tasks, indent=2, ensure_ascii=False))
    tmp.replace(path)


def _cron(args):
    import tools.cronjob_tools  # noqa: F401  registers cronjob_manage
    from tools.registry import registry
    out = registry.dispatch("cronjob_manage", args)
    out = json.loads(out) if isinstance(out, str) else out
    if not out.get("success", True) or (out.get("error") and not out.get("success")):
        raise RuntimeError(out.get("error") or str(out)[:300])
    return out


def _slug(text):
    words = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:32].strip("-") or "task"
    return f"{words}-{secrets.token_hex(2)}"


def create(schedule, prompt, settings, name=""):
    """Schedule ``prompt`` for agy; returns the task (job_id, name, schedule, next_run_at)."""
    prompt, schedule = prompt.strip(), schedule.strip()
    if not prompt or not schedule:
        raise ValueError("a schedule and a prompt are required")
    name = (name or " ".join(prompt.split())[:40]).strip()
    slug = _slug(name)
    task = {"name": name, "prompt": prompt, "agy_bin": settings["agy_bin"],
            "workspace": settings["workspace"], "model": settings.get("model") or "",
            "timeout_minutes": settings["timeout_minutes"], "user": settings["user"],
            "mark": settings["mark"]}
    script = HERMES_HOME / "scripts" / SCRIPTS_SUBDIR / f"{slug}.py"
    script.parent.mkdir(parents=True, exist_ok=True)
    script.write_text(SCRIPT_TEMPLATE.format(task=json.dumps(task, ensure_ascii=False), runner=str(RUNNER)))
    try:
        out = _cron({"action": "create", "name": NAME_PREFIX + name, "schedule": schedule,
                     "script": f"{SCRIPTS_SUBDIR}/{slug}.py", "no_agent": True,
                     "deliver": f"telegram:{settings['chat_id']}"})
    except Exception:
        script.unlink(missing_ok=True)
        raise
    job = out.get("job") or out
    job_id = job.get("job_id") or out.get("job_id")
    with _lock:
        tasks = _load()
        tasks[job_id] = {"name": name, "prompt": prompt, "slug": slug}
        _save(tasks)
    return {"job_id": job_id, "name": name, "schedule": job.get("schedule") or schedule,
            "next_run_at": job.get("next_run_at")}


def list_tasks():
    """agy's tasks still known to Hermes' cron, in creation order."""
    tasks = _load()
    jobs = {j["job_id"]: j for j in _cron({"action": "list"}).get("jobs", [])}
    out = []
    for job_id, task in tasks.items():
        job = jobs.get(job_id)
        if job is None:
            continue
        out.append({"job_id": job_id, "name": task["name"], "prompt": task["prompt"],
                    "schedule": job.get("schedule"), "next_run_at": job.get("next_run_at"),
                    "last_status": job.get("last_status"), "state": job.get("state")})
    return out


def remove(job_id):
    with _lock:
        tasks = _load()
        task = tasks.pop(job_id, None)
        if task is None:
            raise KeyError(job_id)
        try:
            _cron({"action": "remove", "job_id": job_id})
        except RuntimeError:
            pass  # already gone from Hermes' side
        (HERMES_HOME / "scripts" / SCRIPTS_SUBDIR / f"{task['slug']}.py").unlink(missing_ok=True)
        _save(tasks)
    return task


def run_now(job_id):
    if job_id not in _load():
        raise KeyError(job_id)
    return _cron({"action": "run", "job_id": job_id})
