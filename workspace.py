def _tools_section():
    notes = [f"- {TOOL_NOTES[t].format(chat_id=CHAT_ID)}" for t in TOOL_NOTES if t in cfg["bridge_tools"]]
    if cfg["share_mcp_servers"]:
        notes.append("- The MCP servers configured in Hermes: same access as Hermes.")
    return ("## Tools on top of yours (MCP server \"hermes\")\n" + "\n".join(notes)) if notes else ""



def prepare(now=None):
    """(Re)write the workspace; returns a summary for /agy_doctor. Never raises."""
    summary = {"skills": 0, "mcp_servers": [], "rules_bytes": 0, "errors": []}
    for step in (_write_plugin_shell, _write_skills, _write_mcp, _write_rules):
        try:
            step(summary, now or datetime.now().astimezone())
        except Exception as e:
            logger.exception("agy-chat: workspace step %s failed", step.__name__)
            summary["errors"].append(f"{step.__name__}: {e}")
    return summary


def first_turn_preamble():
    """Safety net for the first message of a conversation, should agy not load workspace rules."""
    return (f"(Context: your rules file {RULES_FILE} describes this Telegram channel, your tools and what "
            f"Hermes knows about {USER}. If it isn't already in your rules, read it before answering.)")


def _write_plugin_shell(summary, now):
    for d in (INBOX, OUTBOX, RULES_FILE.parent):
        d.mkdir(parents=True, exist_ok=True)
    _write_if_changed(AGY_PLUGIN / "plugin.json", json.dumps({"name": "hermes"}, indent=2) + "\n")


def _write_rules(summary, now):
    parts = [RULES_HEAD.format(user=USER, inbox=_home(INBOX), outbox=_home(OUTBOX)).rstrip(), _tools_section()]
    if cfg["share_skills"]:
        parts.append(SKILLS_SECTION.format(hermes_home=_home(HERMES_HOME), skills_index=SKILLS_INDEX))
    parts.append(f"## Now\n{now:%A %d %B %Y, %H:%M} (machine time, {now.tzname()}).")
    if MACHINE_NOTES:
        parts.append(f"## Machine\n{MACHINE_NOTES}")
    for title, rel, shared in (
            ("Hermes' personality (SOUL.md) — adopt this tone", "SOUL.md", cfg["share_soul"]),
            (f"What Hermes knows about {USER} (USER.md, entries separated by §)", "memories/USER.md",
             cfg["share_memory"]),
            ("Hermes' memory (MEMORY.md, entries separated by §)", "memories/MEMORY.md", cfg["share_memory"])):
        body = _read(HERMES_HOME / rel) if shared else ""
        if body:
            parts.append(f"## {title}\n{body}")
    thread = hermes_thread(THREAD_MESSAGES) if cfg["share_thread"] else ""
    if thread:
        parts.append(f"## Recent Telegram thread between {USER} and Hermes (for context, don't answer it)\n"
                     + thread)
    text = "\n\n".join(p for p in parts if p) + "\n"
    _write_if_changed(RULES_FILE, text)
    summary["rules_bytes"] = len(text.encode())


def hermes_thread(limit):
    """The user's recent Telegram messages with Hermes, one line each, oldest first."""
    try:
        from hermes_state_registry import acquire, release_or_close
    except ImportError:
        return ""
    db = acquire()
    try:
        row = next((r for r in db.list_gateway_sessions(active_only=True)
                    if r.get("session_key") == session_key()), None)
        if row is None:
            return ""
        lines = []
        for msg in db.get_messages(row["id"]):
            content = msg.get("content")
            if msg.get("role") not in ("user", "assistant") or not isinstance(content, str):
                continue
            text = " ".join(content.split())
            if not text:
                continue
            if len(text) > THREAD_MSG_CHARS:
                text = text[:THREAD_MSG_CHARS - 1] + "…"
            who = USER if msg["role"] == "user" else "Hermes"
            lines.append(f"- {_hhmm(msg.get('timestamp'))} {who}: {text}")
        return "\n".join(lines[-limit:])
    except Exception:
        logger.warning("agy-chat: cannot read the Hermes thread", exc_info=True)
        return ""
    finally:
        release_or_close(db)


def _hhmm(ts):
    try:
        return datetime.fromtimestamp(float(ts)).strftime("%Y-%m-%d %H:%M")
    except (TypeError, ValueError, OSError):
        return ""


def _write_skills(summary, now):
    import yaml
    root = HERMES_HOME / "skills"
    disabled = _disabled_skills()
    by_parent, index = {}, []
    for skill_md in (sorted(root.glob("**/SKILL.md")) if cfg["share_skills"] else ()):
        rel = skill_md.parent.relative_to(root)
        name = skill_md.parent.name
        if any(p.startswith(".") for p in rel.parts) or name in SKILLS_SKIPPED or name in disabled:
            continue
        try:
            head = skill_md.read_text().split("---", 2)
            meta = (yaml.safe_load(head[1]) if len(head) == 3 else {}) or {}
        except (OSError, yaml.YAMLError):
            continue
        desc = " ".join(str(meta.get("description") or "").split())
        index.append(f"- {meta.get('name') or name} — {desc} ({skill_md})")
        if _PLAIN_NAME.match(name):
            by_parent.setdefault(str(skill_md.parent.parent), []).append(name)
    entries = [{"path": parent, "include_only": names} for parent, names in sorted(by_parent.items())]
    _write_if_changed(SKILLS_JSON, json.dumps({"entries": entries}, indent=2) + "\n")
    _write_if_changed(SKILLS_INDEX, "# Hermes' skills\n\nRead the SKILL.md shown before acting.\n\n"
                      + "\n".join(index) + "\n")
    summary["skills"] = len(index)


def _disabled_skills():
    try:
        from agent.skill_utils import get_disabled_skill_names
        return set(get_disabled_skill_names(platform="telegram"))
    except Exception:
        return set()


def _write_mcp(summary, now):
    from . import task_settings
    servers = {}
    if cfg["bridge_tools"]:
        servers["hermes"] = {"command": str(HERMES_PYTHON), "args": [str(BRIDGE)],
                             "env": {"HERMES_HOME": str(HERMES_HOME), "AGY_CHAT_CHAT_ID": CHAT_ID,
                                     "AGY_CHAT_USER": USER, "AGY_CHAT_TOOLS": ",".join(cfg["bridge_tools"]),
                                     "AGY_CHAT_TASK": json.dumps(task_settings(), ensure_ascii=False)}}
    if cfg["share_mcp_servers"]:
        for name, spec in _hermes_mcp_servers().items():
            if name not in servers:
                servers[name] = spec
    text = json.dumps({"mcpServers": servers}, indent=2) + "\n"
    _write_if_changed(MCP_CONFIG, text, mode=0o600)  # carries the MCP servers' bearer tokens
    summary["mcp_servers"] = sorted(servers)


def _hermes_mcp_servers():
    """Hermes' enabled MCP servers, in agy's mcp_config.json shape."""
    import yaml
    try:
        config = yaml.safe_load((HERMES_HOME / "config.yaml").read_text()) or {}
    except (OSError, yaml.YAMLError):
        return {}
    out = {}
    for name, spec in (config.get("mcp_servers") or {}).items():
        if not isinstance(spec, dict) or spec.get("enabled") is False:
            continue
        if spec.get("url"):
            entry = {"url": spec["url"]}
            if spec.get("headers"):
                entry["headers"] = dict(spec["headers"])
        elif spec.get("command"):
            entry = {"command": spec["command"], "args": list(spec.get("args") or [])}
            if spec.get("env"):
                entry["env"] = dict(spec["env"])
        else:
            continue
        out[str(name)] = entry
    return out


def _home(path):
    return str(path).replace(str(HOME), "~", 1)


def _read(path):
    try:
        return path.read_text().strip()
    except OSError:
        return ""


def _write_if_changed(path, text, mode=None):
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        if path.read_text() == text:
            return
    except OSError:
        pass
    tmp = path.with_name(f".{path.name}.tmp")
    tmp.write_text(text)
    if mode is not None:
        os.chmod(tmp, mode)
    tmp.replace(path)

